module sfm_riscv_NbitMux_sv # (parameter int WIDTH = 32, SelNum = 4, SelWidth = 2)(input logic [SelNum-1:0][WIDTH-1:0]muxInput, input logic [SelWidth-1:0]Sel, output logic [WIDTH-1:0]out);

///////////////////////////////////////////////////////INTERNAL LOGIC///////////////////////////////////////////////////////

always_comb begin
	if (Sel < SelNum) begin		//Ensures select is valid
		out = muxInput[Sel];		//Selects
	end else begin					//If it's not valid
		out = '0;					//Set to 0
	end
end

endmodule
