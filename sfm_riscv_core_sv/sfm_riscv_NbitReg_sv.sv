module sfm_riscv_NbitReg_sv # (parameter int WIDTH)(input logic [WIDTH-1:0]D, input logic clk, rst, output logic [WIDTH-1:0]Q);

///////////////////////////////////////////////////////INTERNAL LOGIC///////////////////////////////////////////////////////

always_ff @(posedge clk or posedge rst) begin
	if (rst) begin
		Q <= '0;
	end else begin
		Q <= D;
	end
end

endmodule
