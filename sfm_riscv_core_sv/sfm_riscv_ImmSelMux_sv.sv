module sfm_riscv_ImmSelMux_sv # (parameter int WIDTH = 32)(input logic [3:0]ImmIW, input logic [WIDTH-1:0]I, S, B, U, J, output logic [WIDTH-1:0]Imm);

///////////////////////////////////////////////////////INTERNAL LOGIC///////////////////////////////////////////////////////

	always_comb begin
		case (ImmIW)
			4'b0000 : Imm = I;
			4'b0100 : Imm = S;
			4'b1100 : Imm = B;
			4'b0101 : Imm = U;
			4'b1111 : Imm = J;
			default : Imm = 32'b0;
		endcase
	end
	
endmodule
