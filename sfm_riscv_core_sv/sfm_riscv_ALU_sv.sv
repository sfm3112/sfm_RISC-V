module sfm_riscv_ALU_sv # (parameter int WIDTH = 32)(input logic [WIDTH-1:0]intA, intB, input logic [2:0]Func3, input logic Func7, output logic [WIDTH-1:0]ALUres);

/////////////////////////////////////////////////////////WIRE NAMES/////////////////////////////////////////////////////////

logic [WIDTH-1:0]addSubRes, SLLres, SLTres, SLTUres, XORres, SrlSraRes, ORres, ANDres;

///////////////////////////////////////////////////////INTERNAL LOGIC///////////////////////////////////////////////////////

//////////////////////////////////////////////////////FINAL OUTPUT MUX//////////////////////////////////////////////////////

always_comb begin
	unique case (Func3)
		3'b000 : ALUres = addSubRes;
		3'b001 : ALUres = SLLres;
		3'b010 : ALUres = SLTres;
		3'b011 : ALUres = SLTUres;
		3'b100 : ALUres = XORres;
		3'b101 : ALUres = SrlSraRes;
		3'b110 : ALUres = ORres;
		3'b111 : ALUres = ANDres;
		default : ALUres = '0;
	endcase
end
	
//////////////////////////////////////////////////////////ADD-SUB///////////////////////////////////////////////////////////

assign addSubRes = intA + (intB ^ {WIDTH{Func7}}) + Func7;

//////////////////////////////////////////////////////////SLLres////////////////////////////////////////////////////////////

assign SLLres = intA << intB[4:0];

//////////////////////////////////////////////////////////SLTres////////////////////////////////////////////////////////////

assign SLTres = WIDTH'($signed(intA) < $signed(intB));

//////////////////////////////////////////////////////////SLTUres///////////////////////////////////////////////////////////

assign SLTUres = WIDTH'($unsigned(intA) < $unsigned(intB));

//////////////////////////////////////////////////////////XORres////////////////////////////////////////////////////////////

assign XORres = intA ^ intB;

/////////////////////////////////////////////////////////SrlSraRes//////////////////////////////////////////////////////////

always_comb begin
	unique case (Func7)
		1'b0 : SrlSraRes = intA >> intB[4:0];
		1'b1 : SrlSraRes = $signed(intA) >>> intB[4:0];
		default : SrlSraRes = '0;
	endcase
end

///////////////////////////////////////////////////////////ORres////////////////////////////////////////////////////////////

assign ORres = intA | intB;

///////////////////////////////////////////////////////////ANDres///////////////////////////////////////////////////////////

assign ANDres = intA & intB;

endmodule
